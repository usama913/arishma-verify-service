using Arishma.Verify.Application;
using Arishma.Verify.Infrastructure;
var builder = WebApplication.CreateBuilder(args);
builder.Services.AddHealthChecks();
builder.Services.AddPersistence(builder.Configuration);
var app = builder.Build();
app.MapHealthChecks("/health");
app.MapGet("/", (DatabaseSettings s) => new ServiceInfoDto("Verify", "verify.arishmasolutions.com", "Phase 0 scaffold - DDD, separate repo", s.Provider.ToString()));
app.MapGet("/api/v1/service", (DatabaseSettings s) => new ServiceInfoDto("Verify", "verify.arishmasolutions.com", "Phase 0 scaffold", s.Provider.ToString()));
app.MapGet("/api/v1/verifications", (IVerificationRepository repo) => repo.ListAsync());
app.Run();
